#!/usr/bin/env bash
# Run the real deploy path against a local AWS emulator (moto server): Makefile, preflight,
# Terraform bootstrap and spike stacks, run_spike.sh, destroy. The two spike hosts are simulated
# (moto starts no VMs): a fake host uploads results and terminates its instance.
#
# Proves: Terraform wiring and policies are accepted by an AWS API, the orchestration order,
# approval prompt, destroy on every exit, traceability and the summary file.
# Does NOT prove: Free-plan limits, real quotas and prices, that EKS really becomes ACTIVE, or
# anything that happens on a real host (vLLM, llama.cpp). Those need the real `make spike`.
#
#   make test-aws-local     (needs: moto[server], AWS CLI v2, terraform >= 1.10)
# Report: build/results/local-aws-<time>/report.md
set -uo pipefail

ROOT=$(cd "$(dirname "$0")/../.." && pwd)
cd "$ROOT" || exit 2
PORT=${MOTO_PORT:-5055}
URL="http://127.0.0.1:$PORT"
ACCOUNT=123456789012          # moto's fixed account
REGION=ap-southeast-2
RES="$ROOT/build/results/local-aws-$(date -u +%Y%m%dT%H%M%SZ)"
mkdir -p "$RES"
REPORT="$RES/report.md"
WORK=$(mktemp -d)
PASSED=0; FAILED=0

pass() { echo "| PASS | $1 |" >>"$REPORT"; PASSED=$((PASSED + 1)); }
fail() { echo "| **FAIL** | $1 |" >>"$REPORT"; FAILED=$((FAILED + 1)); }
expect() { local d=$1; shift; if "$@" >/dev/null 2>&1; then pass "$d"; else fail "$d"; fi; }

for tool in moto_server aws terraform; do
  command -v "$tool" >/dev/null || { echo "missing $tool (pip install 'moto[server]'; AWS CLI v2; terraform)"; exit 2; }
done
aws --version 2>&1 | grep -q 'aws-cli/2' || { echo "AWS CLI v2 required"; exit 2; }

# ------------------------------------------------------------------ emulator and credentials
MOTO_IAM_LOAD_MANAGED_POLICIES=true moto_server -H 127.0.0.1 -p "$PORT" >"$RES/moto.log" 2>&1 &
MOTO_PID=$!
python3 "$ROOT/scripts/local_aws/forward_proxy.py" "$((PORT + 1))" "$PORT" &
PROXY_PID=$!
cleanup() {
  rm -f infra/bootstrap/zz_local_aws_override.tf infra/spike/zz_local_aws_override.tf
  rm -rf "$ROOT/infra/bootstrap/.terraform-local" "$ROOT/infra/spike/.terraform-local"
  kill "$MOTO_PID" "$PROXY_PID" 2>/dev/null
  rm -rf "$WORK"
}
trap cleanup EXIT
for _ in $(seq 30); do curl -sf "$URL/moto-api/" >/dev/null && break; sleep 1; done

# A throwaway profile named like the real one; nothing here can reach real AWS.
cat >"$WORK/config" <<EOF
[profile inference-lab]
region = $REGION
endpoint_url = $URL
aws_access_key_id = testing
aws_secret_access_key = testing
EOF
unset AWS_ACCESS_KEY_ID AWS_SECRET_ACCESS_KEY AWS_SESSION_TOKEN AWS_CREDENTIAL_EXPIRATION
export AWS_CONFIG_FILE="$WORK/config" AWS_SHARED_CREDENTIALS_FILE="$WORK/none"
export AWS_PROFILE=inference-lab AWS_REGION=$REGION AWS_ENDPOINT_URL=$URL AWS_EC2_METADATA_DISABLED=true
# Account-prefixed hosts (S3 Control) cannot resolve; plain-HTTP requests go through the
# forwarding proxy instead. Loopback IPs are never proxied, so ordinary calls stay direct.
# NO_PROXY must not list 127.0.0.1: Go treats it as a suffix and would bypass the proxy.
export HTTP_PROXY="http://127.0.0.1:$((PORT + 1))" http_proxy="http://127.0.0.1:$((PORT + 1))"
export NO_PROXY=localhost no_proxy=localhost
# Keep the emulator's Terraform working data apart from the real one (relative to each -chdir).
export TF_DATA_DIR=.terraform-local
aws sts get-caller-identity --query Account --output text | grep -q "$ACCOUNT" || { echo "emulator not answering"; exit 2; }

# Point Terraform's provider and S3 backend at the emulator without touching the real files.
for stack in bootstrap spike; do
  cat >"infra/$stack/zz_local_aws_override.tf" <<EOF
# Generated by scripts/local_aws/test.sh; deleted on exit; never committed (*_override.tf).
terraform {
  backend "s3" {
    key                         = "inference-lab/$stack.tfstate"
    encrypt                     = true
    use_lockfile                = true
    use_path_style              = true
    skip_credentials_validation = true
    skip_requesting_account_id  = true
    skip_metadata_api_check     = true
    endpoints = { s3 = "$URL", sts = "$URL" }
  }
}
provider "aws" {
  s3_use_path_style           = true
  skip_credentials_validation = true
  skip_metadata_api_check     = true
  endpoints {
    ec2 = "$URL"
    eks = "$URL"
    iam = "$URL"
    s3  = "$URL"
    ssm = "$URL"
    sts = "$URL"
  }
}
EOF
done

# What already exists in the real account (from pipeline-triage-agent).
aws s3api create-bucket --bucket "triage-tfstate-$ACCOUNT-$REGION" \
  --create-bucket-configuration LocationConstraint=$REGION >/dev/null
aws secretsmanager create-secret --name triage/anthropic-api-key --secret-string not-a-real-key >/dev/null

{
  echo "# Local AWS emulator test $(date -u +%FT%TZ)"
  echo
  echo "Emulator: moto $(python3 -c 'import moto;print(moto.__version__)' 2>/dev/null || echo '?'), \
$(aws --version 2>&1 | cut -d' ' -f1), $(terraform version | head -1). Commit $(git rev-parse --short HEAD)."
  echo
  echo "| Result | Check |"
  echo "|---|---|"
} >"$REPORT"

# ------------------------------------------------------------------ 1. bootstrap via the Makefile
echo yes | make bootstrap >"$RES/bootstrap.txt" 2>&1
expect "make bootstrap applies (boundary + artifacts bucket)" grep -q "Apply complete" "$RES/bootstrap.txt"
BUCKET="inference-lab-artifacts-$ACCOUNT-$REGION"
BOUNDARY="arn:aws:iam::$ACCOUNT:policy/inference-lab/inference-lab-workload-boundary"
expect "Artifacts bucket exists" aws s3api head-bucket --bucket "$BUCKET"
expect "Boundary policy exists at /inference-lab/" aws iam get-policy --policy-arn "$BOUNDARY"
expect "Bootstrap state written with a lock-file backend" \
  aws s3api head-object --bucket "triage-tfstate-$ACCOUNT-$REGION" --key inference-lab/bootstrap.tfstate

# ------------------------------------------------------------------ 2. preflight
GAPS="vcpu_quota"   # Service Quotas for EC2 is not emulated by moto
PREFLIGHT_EMULATOR_GAPS=$GAPS OUT_DIR="$RES/preflight" ./scripts/preflight.sh >"$RES/preflight.txt" 2>&1
expect "Preflight passes on a clean account (gaps shown as SKIP: $GAPS)" grep -q "Preflight passed" "$RES/preflight.txt"
AWS_ACCESS_KEY_ID=AKIAFAKE PREFLIGHT_EMULATOR_GAPS=$GAPS OUT_DIR="$RES/preflight-bad" \
  ./scripts/preflight.sh >"$RES/preflight-bad.txt" 2>&1
expect "Preflight fails when static keys are exported" grep -q "Preflight FAILED" "$RES/preflight-bad.txt"

# ------------------------------------------------------------------ 3. spike declined
echo no | PREFLIGHT_EMULATOR_GAPS=$GAPS ./scripts/run_spike.sh >"$RES/spike-declined.txt" 2>&1
expect "Answering 'no' applies nothing" grep -q "Not applied." "$RES/spike-declined.txt"
n=$(aws ec2 describe-instances --filters Name=instance-state-name,Values=pending,running \
  --query 'length(Reservations[].Instances[])' --output text)
expect "No instances after 'no'" test "$n" = 0

# ------------------------------------------------------------------ 4. spike approved, hosts simulated
fake_hosts() {  # wait for the instances, then behave like spike.sh + user-data on each
  local run ids
  for _ in $(seq 120); do
    run=$(cat build/spike_run_id 2>/dev/null)
    ids=$(aws ec2 describe-instances --filters Name=tag:stack,Values=spike Name=instance-state-name,Values=running \
      --query 'Reservations[].Instances[].[InstanceId,Tags[?Key==`Name`]|[0].Value]' --output text)
    [ "$(echo "$ids" | grep -c .)" -ge 2 ] && break
    sleep 2
  done
  # A real host needs minutes before it can shut down; finish only after the apply has.
  for _ in $(seq 300); do
    grep -qE 'Apply complete|Error' "build/results/spike-$run/apply.txt" 2>/dev/null && break
    sleep 2
  done
  echo "$ids" >"$RES/fake_hosts.txt"
  while read -r id name; do
    local label=${name##*-}
    printf 'step\tstatus\tseconds\ninstall_tools\tok\t1\nwrite_summary\tok\t1\n' >"$WORK/steps.tsv"
    printf '# Spike: %s (simulated host) run %s\n' "$label" "$run" >"$WORK/spike-summary.md"
    aws s3 cp --quiet "$WORK/steps.tsv" "s3://$BUCKET/spike/$run/$label/steps.tsv"
    aws s3 cp --quiet "$WORK/spike-summary.md" "s3://$BUCKET/spike/$run/$label/spike-summary.md"
    aws ec2 terminate-instances --instance-ids "$id" >/dev/null   # what shutdown -h does
  done <<<"$ids"
}

capture_before_destroy() {  # inspect what the apply created while it exists
  for _ in $(seq 120); do
    [ "$(wc -l <"$RES/fake_hosts.txt" 2>/dev/null || echo 0)" -ge 2 ] && break; sleep 2
  done
  aws ec2 describe-instances --filters Name=tag:stack,Values=spike >"$RES/instances.json"
  aws iam get-role --role-name inference-lab-spike >"$RES/role-spike.json" 2>&1
  aws iam get-role --role-name inference-lab-eks-probe >"$RES/role-eks.json" 2>&1
  aws eks describe-cluster --name inference-lab-probe >"$RES/eks.json" 2>&1
  aws s3 cp --quiet "s3://$BUCKET/spike/$(cat build/spike_run_id)/bundle.zip" "$RES/bundle.zip"
  local id; id=$(head -1 "$RES/fake_hosts.txt" | cut -f1)
  aws ec2 describe-instance-attribute --instance-id "$id" --attribute userData \
    --query UserData.Value --output text | base64 -d >"$RES/user-data.sh" 2>/dev/null
  aws ec2 describe-instance-attribute --instance-id "$id" --attribute instanceInitiatedShutdownBehavior \
    --query InstanceInitiatedShutdownBehavior.Value --output text >"$RES/shutdown-behavior.txt" 2>&1
}

capture_before_destroy &
CAP=$!
fake_hosts &
FAKE=$!
echo yes | PREFLIGHT_EMULATOR_GAPS=$GAPS MAX_MINUTES=5 SPIKE_POLL_SECONDS=5 SPIKE_GRACE_MINUTES=1 \
  ./scripts/run_spike.sh >"$RES/spike.txt" 2>&1
wait "$FAKE" "$CAP"
RUN=$(cat build/spike_run_id)
SUMMARY="build/results/spike-$RUN/summary.md"

expect "Spike apply succeeded" grep -q "Apply: ok" "$SUMMARY"
expect "Two hosts launched" test "$(grep -c . "$RES/fake_hosts.txt")" = 2
expect "Graviton host is c8g.2xlarge arm64" python3 -c "
import json,sys;r=json.load(open('$RES/instances.json'))['Reservations']
i=[x for y in r for x in y['Instances'] if any(t['Value'].endswith('graviton') for t in x['Tags'] if t['Key']=='Name')][0]
sys.exit(0 if i['InstanceType']=='c8g.2xlarge' else 1)"
expect "Every instance tagged project=inference-lab" python3 -c "
import json,sys;r=json.load(open('$RES/instances.json'))['Reservations']
sys.exit(0 if all({'Key':'project','Value':'inference-lab'} in x['Tags'] for y in r for x in y['Instances']) else 1)"
expect "IMDSv2 required on every instance" python3 -c "
import json,sys;r=json.load(open('$RES/instances.json'))['Reservations']
sys.exit(0 if all(x['MetadataOptions']['HttpTokens']=='required' for y in r for x in y['Instances']) else 1)"
expect "Instances terminate on shutdown (hard cap works)" grep -q terminate "$RES/shutdown-behavior.txt"
expect "User-data rendered with bucket and run id" grep -q "s3://$BUCKET/spike/$RUN/bundle.zip" "$RES/user-data.sh"
expect "Rendered user-data is valid bash" bash -n "$RES/user-data.sh"
expect "Spike role carries the boundary" grep -q "$BOUNDARY" "$RES/role-spike.json"
expect "EKS probe role carries the boundary" grep -q "$BOUNDARY" "$RES/role-eks.json"
expect "EKS probe cluster was created" grep -q '"name": "inference-lab-probe"' "$RES/eks.json"
expect "Harness bundle uploaded with the commit stamp" \
  bash -c "unzip -p $RES/bundle.zip .bundle-commit | grep -q $(git rev-parse HEAD)"
expect "Bundle has no secrets, venv or build output" \
  bash -c "unzip -Z1 $RES/bundle.zip | grep -q spike.sh && ! unzip -Z1 $RES/bundle.zip | grep -E '\.venv/|build/|\.tfstate|\.git/|override'"
expect "Summary has both host sections" bash -c "grep -q 'graviton (simulated' $SUMMARY && grep -q 'x86 (simulated' $SUMMARY"
expect "Summary records the commit" grep -q "$(git rev-parse HEAD)" "$SUMMARY"
expect "Destroy ran" grep -q "Destroyed." "$RES/spike.txt"
expect "No inference-lab instances left" test -z "$(aws ec2 describe-instances --filters Name=tag:project,Values=inference-lab \
  Name=instance-state-name,Values=pending,running,stopping,stopped --query 'Reservations[].Instances[].InstanceId' --output text)"
expect "No EKS cluster left" test -z "$(aws eks list-clusters --query clusters --output text)"
expect "Spike roles removed" bash -c "! aws iam get-role --role-name inference-lab-spike"
expect "Spike state is empty" bash -c "terraform -chdir=infra/spike state list | grep -c . | grep -qx 0"
expect "Bootstrap kept (boundary, bucket survive the nightly destroy)" aws iam get-policy --policy-arn "$BOUNDARY"

# ------------------------------------------------------------------ 5. hosts that never finish
echo yes | PREFLIGHT_EMULATOR_GAPS=$GAPS MAX_MINUTES=1 SPIKE_POLL_SECONDS=10 SPIKE_GRACE_MINUTES=0 \
  ./scripts/run_spike.sh >"$RES/spike-hung.txt" 2>&1
expect "Hung hosts: deadline is reported" grep -q "Deadline reached" "$RES/spike-hung.txt"
expect "Hung hosts: destroy still runs" grep -q "Destroyed." "$RES/spike-hung.txt"
expect "Hung hosts: nothing left running" test -z "$(aws ec2 describe-instances --filters Name=tag:project,Values=inference-lab \
  Name=instance-state-name,Values=pending,running,stopping,stopped --query 'Reservations[].Instances[].InstanceId' --output text)"

{
  echo
  echo "**$PASSED passed, $FAILED failed.** Logs and captured AWS objects: \`$RES/\`."
  echo
  echo "Not covered by the emulator: Free-plan limits, EC2 vCPU quota, prices, real EKS readiness,"
  echo "and everything that runs on the hosts (vLLM, llama.cpp). Those are proven by \`make spike\`."
} >>"$REPORT"
cat "$REPORT"
[ "$FAILED" -eq 0 ]
